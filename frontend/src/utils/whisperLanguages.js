export function getWhisperLanguageLabel(code) {
  if (!code || code === 'auto') return 'Auto-Detect';
  const found = WHISPER_LANGUAGES.find(l => l.code === code.toLowerCase());
  return found ? found.name : code.toUpperCase();
}

